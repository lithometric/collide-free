/// The committed pin: this version's SHA-256 per platform, one line each,
/// so a shell and a reviewer read it without a JSON parser. `None` when this
/// server has no builds. Python's `blocks.hooks_lock`, byte for byte.
pub fn hooks_lock(builds: &[Value], version: i64) -> Option<String> {
    let mut pins: Vec<(String, String)> = builds
        .iter()
        .filter_map(|b| {
            let target = b.get("target").and_then(Value::as_str).filter(|t| !t.is_empty())?;
            let sha = b.get("sha256").and_then(Value::as_str).filter(|h| !h.is_empty())?;
            Some((target.to_string(), sha.to_string()))
        })
        .collect();
    if pins.is_empty() {
        return None;
    }
    pins.sort();
    let mut lines = vec![
        "# Collide's native hook, pinned by setup. Commit this file.".to_string(),
        "# A new machine downloads exactly the build listed for its platform and refuses".to_string(),
        "# any file whose SHA-256 differs. Updates after that must be signed by the key below.".to_string(),
        format!("version {version}"),
        format!("key {HOOK_SIGNING_KEY}"),
    ];
    lines.extend(pins.into_iter().map(|(target, sha)| format!("{target} {sha}")));
    Some(lines.join("\n") + "\n")
}
