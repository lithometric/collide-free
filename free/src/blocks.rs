/// Committable per-repo hook config (no secrets; the token lives in each
/// user's `~/.collide/credentials.json`).
pub fn collide_config_json(server_url: &str, repo_id: &str, workspace: &str) -> Value {
    let mut config = Map::new();
    config.insert("server_url".into(), json!(server_url.trim_end_matches('/')));
    config.insert("repo_id".into(), json!(repo_id));
    if !workspace.is_empty() {
        config.insert("workspace".into(), json!(workspace));
    }
    // the native hook parses on the machine and sends the structure the
    // server keeps, never the file (the Python fallback still sends files)
    config.insert("local_parse".into(), json!(true));
    Value::Object(config)
}

/// PostToolUse blocks: every Edit/Write auto-reports, every Read/Grep/Glob
/// posts presence. All modes.
pub fn report_hooks() -> Value {
    let hook = json!({"type": "command", "command": REPORT_HOOK_COMMAND, "timeout": 5});
    json!({
        "PostToolUse": [
            {"matcher": "Edit|Write|MultiEdit|NotebookEdit", "hooks": [hook.clone()]},
            {"matcher": "Read|Grep|Glob|Bash", "hooks": [hook.clone()]},
        ],
        // a failed call sends no PostToolUse: without this, a session whose
        // commands failed showed as no agent running
        "PostToolUseFailure": [
            {"matcher": "Edit|Write|MultiEdit|NotebookEdit|Read|Grep|Glob|Bash", "hooks": [hook.clone()]},
        ],
        "Stop": [{"hooks": [hook.clone()]}],
        // the session ended: the agent leaves the Now panel the moment it is
        // gone, instead of an hour later when silence is taken for absence
        "SessionEnd": [{"hooks": [hook.clone()]}],
        // a batch of writes landed: the repo's check runs detached, its
        // verdict rides the next event
        "PostToolBatch": [{"hooks": [{"type": "command", "command": REPORT_HOOK_COMMAND, "timeout": 10}]}],
        // the task is known: the briefing narrows to what the prompt names
        "UserPromptSubmit": [{"hooks": [{"type": "command", "command": REPORT_HOOK_COMMAND, "timeout": 10}]}],
        // the agent just wrote these very hooks into settings.json, and this
        // firing proves they loaded. Without it the setup nag clears only on
        // the first file WRITE, so a session that installs the hooks and then
        // only reads keeps being told to install them.
        "ConfigChange": [{"matcher": "project_settings|local_settings|user_settings",
                          "hooks": [{"type": "command", "command": REPORT_HOOK_COMMAND, "timeout": 5}]}],
    })
}

/// Claude Code hook blocks. Report hook ships in every mode; the gate only
/// in enforce; SessionStart injects the bootstrap/self-install check.
pub fn hooks_json(server_url: &str, mode: &str) -> Value {
    let mut hooks = report_hooks();
    let map = hooks.as_object_mut().expect("report_hooks() returns an object");
    // the reporter on SessionStart indexes the tracked tree into the map
    // once, then only what changed — a few hundred modules in a few calls
    map.insert(
        "SessionStart".into(),
        json!([{"hooks": [
            {"type": "command", "command": BOOTSTRAP_COMMAND, "timeout": 15},
            {"type": "command", "command": REPORT_HOOK_COMMAND, "timeout": 30},
        ]}]),
    );
    if mode == "enforce" {
        map.insert(
            "PreToolUse".into(),
            json!([{
                "matcher": "Edit|Write|MultiEdit|Bash",
                "hooks": [{"type": "command", "command": GATE_HOOK_COMMAND, "timeout": 5}],
            }]),
        );
    }
    json!({
        "hooks": hooks,
        "server_url": server_url,
    })
}

/// Codex `.codex/hooks.json`. Same matcher+hooks shape; `apply_patch` is
/// Codex's file-edit tool. The PreToolUse gate ships only in enforce mode.
pub fn codex_hooks_json(mode: &str) -> Value {
    let report = json!({
        "type": "command",
        "command": codex_hook_command(HOOK_FILE, "collide-report-hook", false, "codex"),
        "timeout": 5,
    });
    let mut hooks = Map::new();
    hooks.insert(
        "PostToolUse".into(),
        json!([
            {"matcher": "^(apply_patch|Edit|Write|MultiEdit)$", "hooks": [report.clone()]},
            {"matcher": "^(Read|Grep|Glob|Bash|shell)$", "hooks": [report.clone()]},
        ]),
    );
    // the reporter on SessionStart indexes the tracked tree into the map
    // once, then only what changed (inert on a Codex that does not fire it)
    let mut index = report.clone();
    index["timeout"] = json!(30);
    hooks.insert("SessionStart".into(), json!([{"hooks": [index]}]));
    // the task is known: the briefing narrows to what the prompt names
    let mut briefing = report.clone();
    briefing["timeout"] = json!(10);
    hooks.insert("UserPromptSubmit".into(), json!([{"hooks": [briefing]}]));
    // the session ended (Codex fires it on close and after 30 idle minutes):
    // the agent leaves the Now panel the moment it is gone
    hooks.insert("SessionEnd".into(), json!([{"hooks": [report]}]));
    if mode == "enforce" {
        let gate = json!({
            "type": "command",
            "command": codex_hook_command(GATE_HOOK_FILE, "collide-gate-hook", true, "codex"),
            "timeout": 5,
        });
        hooks.insert(
            "PreToolUse".into(),
            json!([{"matcher": "^(apply_patch|Edit|Write|MultiEdit|shell)$", "hooks": [gate]}]),
        );
    }
    json!({"hooks": Value::Object(hooks)})
}

/// Cursor `.cursor/hooks.json`. Cursor names its events in camelCase and
/// reads a JSON decision on stdout rather than an exit code, so the hooks are
/// invoked with `--harness cursor` and translate at both edges; the scripts
/// themselves are the same committed artifacts every other harness runs.
///
/// Five of Collide's seven events have a native home here. There is no
/// batch boundary, so the repo's own check is spawned from `postToolUse` and
/// its verdict rides the next tool result rather than the end of a write
/// batch.
pub fn cursor_hooks_json(mode: &str) -> Value {
    let report = codex_hook_command(HOOK_FILE, "collide-report-hook", false, "cursor");
    let mut hooks = Map::new();
    // the tracked tree joins the map, then the repo briefing prints
    hooks.insert("sessionStart".into(), json!([{"command": report, "timeout": 30}]));
    // the conversation ended: the agent leaves the Now panel at once
    hooks.insert("sessionEnd".into(), json!([{"command": report, "timeout": 5}]));
    // the task is known: the briefing narrows to what the prompt names
    hooks.insert("beforeSubmitPrompt".into(), json!([{"command": report, "timeout": 10}]));
    // every write reported, every read placed, notes ride the tool result
    hooks.insert(
        "postToolUse".into(),
        json!([{"matcher": "^(Write|Edit|MultiEdit|Delete|Read|Glob|Grep|Shell)$",
                "command": report, "timeout": 5}]),
    );
    // the turn ended: a usage limit is the team's business
    hooks.insert("stop".into(), json!([{"command": report, "timeout": 5}]));
    if mode == "enforce" {
        hooks.insert(
            "preToolUse".into(),
            json!([{"matcher": "^(Write|Edit|MultiEdit|Delete|Shell)$",
                    "command": codex_hook_command(GATE_HOOK_FILE, "collide-gate-hook", true, "cursor"),
                    "timeout": 5}]),
        );
    }
    json!({"version": 1, "hooks": Value::Object(hooks)})
}

/// Merge target for the repo's `.claude/settings.json`. Note: always builds
/// its hooks with `server_url=""` — matching Python's `hooks_json(mode=mode)`
/// call, which never passes `server_url` here — because only the `hooks`
/// sub-object is used; the (unused) `server_url` field of that intermediate
/// result is discarded either way.
pub fn claude_settings_json(mode: &str) -> Value {
    let inner = hooks_json("", mode);
    json!({
        "permissions": {"allow": ["mcp__collide"]},
        "enabledMcpjsonServers": ["collide"],
        "hooks": inner.get("hooks").cloned().unwrap_or_else(|| json!({})),
    })
}

