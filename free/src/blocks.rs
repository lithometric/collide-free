/// Codex `.codex/hooks.json` command builder (`_codex_hook_command`). Unlike
/// the Claude Code commands above, Codex sets no `CLAUDE_PROJECT_DIR`, so
/// this one genuinely depends on `hook_file`/`fallback`/`propagate` and is
/// real logic rather than embedded text.
fn codex_hook_command(hook_file: &str, fallback: &str, propagate: bool, harness: &str) -> String {
    let tail = if propagate { "" } else { " 2>/dev/null || true" };
    let subcommand = if propagate { "gate" } else { "report" };
    // Claude Code is the canonical dialect and takes no flag, so every
    // settings.json already committed keeps working byte for byte
    let flag = if harness == "claude" { String::new() } else { format!(" --harness {harness}") };
    let branch = if propagate {
        format!("if [ -n \"$b\" ]; then exec \"$b\" {subcommand}{flag}; fi; ")
    } else {
        format!("if [ -n \"$b\" ]; then \"$b\" {subcommand}{flag} 2>/dev/null || true; exit 0; fi; ")
    };
    format!(
        "d=\"${{CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || echo .)}}\"; \
b=\"$d/{BIN_FILE}\"; [ -x \"$b\" ] || b=\"$(command -v collide-hook 2>/dev/null)\"; {branch}\
f=\"$d/{hook_file}\"; p=\"\"; for c in python3 python py; do command -v \"$c\" >/dev/null 2>&1 || continue; \"$c\" -c \"\" >/dev/null 2>&1 && {{ p=\"$c\"; break; }}; done; \
if [ -f \"$f\" ] && [ -n \"$p\" ]; then \"$p\" \"$f\"{flag}{tail}; else {fallback}{flag} 2>/dev/null || true; fi"
    )
}

