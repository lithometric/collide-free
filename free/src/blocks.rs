    /// The settings digest is the SECOND staleness signal — the one that
    /// catches a settings block wired before a hook change, which the
    /// script's own version can never see. Both halves must agree on it or
    /// the server would call a correct install stale.
    #[test]
    fn settings_digests_match_python() {
        let g = golden();
        assert_eq!(
            settings_digest(&claude_settings_json("enforce")),
            g["settings_digest_claude_enforce"].as_str().unwrap());
        assert_eq!(
            settings_digest(&claude_settings_json("advisory")),
            g["settings_digest_claude_advisory"].as_str().unwrap());
        assert_eq!(
            settings_digest(&codex_hooks_json("enforce")),
            g["settings_digest_codex_enforce"].as_str().unwrap());
        assert_eq!(
            settings_digest(&cursor_hooks_json("enforce")),
            g["settings_digest_cursor_enforce"].as_str().unwrap());
        // somebody else's hooks are not ours: no Collide command, no digest
        let foreign = serde_json::json!({"hooks": {"PostToolUse": [{"hooks": [{"command": "echo hi"}]}]}});
        assert_eq!(settings_digest(&foreign), g["settings_digest_empty"].as_str().unwrap());
        assert_eq!(settings_digest(&foreign), "");

        let current: Vec<String> = current_settings_digests().into_iter().collect();
        let want: Vec<String> = g["current_settings_digests"].as_array().unwrap()
            .iter().map(|v| v.as_str().unwrap().to_string()).collect();
        assert_eq!(current, want);
        // every generated install must be recognised as current
        assert!(current.contains(&settings_digest(&claude_settings_json("enforce"))));
    }

