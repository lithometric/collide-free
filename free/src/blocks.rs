/// Python's `setup` MCP tool: `service.setup()` plus `repo_files` (always)
/// and `user_files` (only when `can_write` — a read-only member gets
/// advisory-mode artifacts with no credential). The optional `native_hook`
/// block Python adds when compiled hook builds exist is not reproduced: no
/// `artifacts.rs` registry has been ported yet, so this always takes the
/// same path Python takes when zero builds are available (silently omit
/// the field) — never a wrong claim, just an honest "not yet checked".
pub fn setup_tool_response(store: &Store, mode: &str, can_write: bool, req: &ArtifactRequest) -> Value {
    // a workspace on Free gets the free version: installed once for every
    // repo on the machine, all of it local (machines.rs)
    if can_write && mode != "files" {
        if let Some(free) = crate::machines::offer_free(store, req.public_url, req.workspace, req.auth_uid, req.email, req.name) {
            return free;
        }
    }
    // a server with a build to pin answers with one command (setupone.rs)
    if let Some(quick) = crate::setupone::offer(store, mode, can_write, req) {
        return quick;
    }
    // "files" only skips the command; the files it returns are enforce mode's
    let mode = if mode == "files" { "enforce" } else { mode };
    let mut result = setup(req.repo_id, mode, req.public_url, req.mcp_url);
    let map = result.as_object_mut().expect("setup() returns an object");

    map.insert("repo_files".into(), json!({
        HOOK_FILE: hook_script_source(),
        GATE_HOOK_FILE: gate_hook_source(),
        CONFIG_FILE: dumps_with_newline(&collide_config_json(req.public_url, req.repo_id, req.workspace)),
        NATIVE_INSTALL_FILE: native_hook_install_script(req.public_url),
    }));
    push_note(map, "repo_files: write into the repo and COMMIT them (the hook scripts + a \
no-secrets config) — every teammate then runs the current hooks with zero installation.");

    // the compiled hooks, offered only when this server has a build to serve:
    // a suggestion to install something that 404s would be worse than silence
    let builds = crate::artifacts::available();
    if let Some(lock) = hooks_lock(&builds, crate::envelope::HOOK_ARTIFACT_VERSION) {
        if let Some(files) = map.get_mut("repo_files").and_then(Value::as_object_mut) {
            files.insert(HOOKS_LOCK_FILE.into(), json!(lock));
        }
    }
    if !builds.is_empty() {
        let index = if req.public_url.is_empty() {
            "/artifacts/hooks".to_string()
        } else {
            format!("{}/artifacts/hooks", req.public_url)
        };
        map.insert("native_hook".into(), json!({
            "why": "the same gate/report/pre-commit/watch logic compiled — about 17x \
faster to start, on something that runs for every tool call",
            "install": format!("sh {NATIVE_INSTALL_FILE}"),
            "index": index,
            "targets": builds.iter().map(|b| b.get("target").cloned().unwrap_or(Value::Null))
                .collect::<Vec<_>>(),
            "optional": true,
        }));
        push_note(map, &format!(
            "native_hook (optional): run `sh {NATIVE_INSTALL_FILE}` once per machine to \
install the compiled hooks. It verifies the digest, installs to .collide/bin/ (gitignore \
that), and changes nothing if this server has no build for the platform — the Python \
hooks keep working either way."));
    }

    if can_write {
        let credentials = mint_hook_credential(store, &req.identity(), "collide-hook", req.public_url);
        mark_hooks_installed(store, req.scope, req.user_id);
        map.insert("user_files".into(), json!({CREDENTIALS_FILE: dumps_with_newline(&credentials)}));
        push_note(map, "user_files: install MERGING, not overwriting — save the JSON content to a \
temp file and run `python .collide/report_hook.py --add-credentials <file>` \
(merges into ~/.collide/credentials.json; other workspaces' credentials \
survive). Per-user, NEVER committed.");
    }
    push_note(map, "Hooks: Claude Code hot-reloads .claude/settings.json within seconds, so the hooks \
just installed normally fire in THIS session already — no restart by default. Keep \
reporting your next write with report_edit: if that response carries \
restart_required, this session missed the change and you must tell the human to \
restart. A NEW .mcp.json entry is different: teammates need a fresh session to \
discover the server (you are already connected to it).");
    result
}

