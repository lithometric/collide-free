/// Return `(new_content, markers_were_present)`. Only the region between
/// the collide markers is replaced; everything outside is byte-identical.
/// Absent markers -> the wrapped block is appended.
pub fn sync_agents_content(file_content: &str, repo_id: &str) -> (String, bool) {
    let block = canonical_block(repo_id);
    let start_idx = file_content.find(START_MARKER);
    let end_idx = start_idx.and_then(|start| {
        file_content[start + START_MARKER.len()..]
            .find(END_MARKER)
            .map(|rel| start + START_MARKER.len() + rel)
    });

    match (start_idx, end_idx) {
        (Some(start), Some(end)) => {
            let prefix = &file_content[..start];
            let suffix = &file_content[end + END_MARKER.len()..];
            (format!("{prefix}{block}{suffix}"), true)
        }
        _ => {
            let mut prefix = file_content.to_string();
            if !prefix.is_empty() && !prefix.ends_with('\n') {
                prefix.push('\n');
            }
            let sep = if prefix.is_empty() { "" } else { "\n" };
            (format!("{prefix}{sep}{block}\n"), false)
        }
    }
}

/// Python's `json.dumps(value, indent=2) + "\n"`, for artifact content that
/// is genuinely written to a file (`.collide/config.json`,
/// `~/.collide/credentials.json`, `.mcp.json`, `.codex/hooks.json`) rather
/// than an ephemeral protocol reply — so it is worth matching Python's
/// formatting exactly rather than any valid JSON rendering. `serde_json`'s
/// pretty-printer produces the identical 2-space/`": "`/no-trailing-comma
/// shape, and this crate's `Map` preserves insertion order (`serde_json`
/// pulls in `indexmap` here), so key order matches too as long as the
/// `Value` was built in the same order as the Python dict literal.
pub(crate) fn dumps_with_newline(value: &Value) -> String {
    format!("{}\n", serde_json::to_string_pretty(value).unwrap_or_else(|_| "{}".into()))
}

