//! Installation artifacts: the canonical AGENTS.md block, the Claude Code /
//! Codex hooks JSON, and the response shapes for the four tools that hand
//! these out (`setup`, `sync_agents_block`, `install_hooks`,
//! `connect_agents`).
//!
//! None of these functions edit a file themselves — same as the Python
//! side. They compute artifacts and (for the tool-response functions) touch
//! the store for the minted credential, the setup ticker, and the ledger
//! row; the caller applies the returned content so the change lands in the
//! *agent's own* diff, not a silent server-side write.
//!
//! ## Byte-for-byte requirements
//!
//! The protocol block text (`_BLOCK_BODY`/`block_body`/`canonical_block`)
//! and the hook shell-command strings are written into a developer's
//! `AGENTS.md`, `.claude/settings.json`, and `.codex/hooks.json`. A
//! reworded byte here is a version bump every client has to re-sync, so
//! this module never retypes that text — it is extracted verbatim from the
//! Python source (`collide/blocks.py`) into sibling `.txt` files and pulled
//! in with `include_str!`:
//!   - `block_body.txt` — the template, `{{`/`}}` already unescaped to
//!     single braces, `{version}`/`{repo_id}` left as literal tokens this
//!     module substitutes at call time.
//!   - `hook_report_command.txt`, `hook_gate_command.txt`,
//!     `hook_bootstrap_command.txt`, `hook_precommit_shim.txt` — these are
//!     module-level constants in Python (computed once from OTHER
//!     constants, never from a function argument), so their resolved text
//!     is stable and is embedded as-is rather than rebuilt at runtime.
//!   - `hook_native_install_template.txt` — same story, `__BASE__` swapped
//!     in by `native_hook_install_script`.
//!
//! Everything that genuinely depends on a call argument (`hooks_json`,
//! `codex_hooks_json`, `collide_config_json`, `mcp_json`, the `*_hook_command`
//! builders that take a hook file / fallback / propagate flag) is real
//! translated logic, checked against a golden dump of the Python output in
//! the `tests` module below (`blocks_golden.json`, generated by running the
//! Python functions with the same inputs).
//!
//! ## Scope boundary
//!
//! `setup_tool_response` / `install_hooks_response` / `connect_agents_response`
//! take an already-resolved [`ArtifactRequest`] rather than an `auth`/`ctx`
//! object: workspace routing (`workspace_for`), scope resolution
//! (`scope_of`), and the read-only access check are the MCP dispatch
//! layer's job (same division every other ported module — `intents.rs`,
//! `report.rs` — already uses). This module mints the hook credential
//! itself (a direct `TOKEN_BUCKET` write, record-compatible with
//! `auth::principal_for_bearer`) since that is inseparable from "what
//! `setup` returns", but it does not resolve identity or workspace.

